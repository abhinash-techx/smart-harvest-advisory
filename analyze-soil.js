let currentLanguage="en", selectedSoilImage=null, userLocation=null;

const $=id=>document.getElementById(id);
const languageSelect=$("languageSelect"), imageAnalysisBtn=$("imageAnalysisBtn"), manualAnalysisBtn=$("manualAnalysisBtn"), kitBtn=$("kitBtn"), labBtn=$("labBtn");
const imageModal=$("imageModal"), manualModal=$("manualModal"), kitModal=$("kitModal"), labModal=$("labModal");
const soilImage=$("soilImage"), fileName=$("fileName"), analyzeImageBtn=$("analyzeImageBtn"), soilForm=$("soilForm");
const soilResult=$("soilResult"), resultContent=$("resultContent");

function t(key){return (translations[currentLanguage]&&translations[currentLanguage][key])||translations.en[key]||key}

function changeLanguage(language){
    if(!translations[language]) language="en";
    currentLanguage=language;
    document.documentElement.lang=language;
    document.querySelectorAll("[data-i18n]").forEach(el=>{
        const key=el.getAttribute("data-i18n");
        if(translations[currentLanguage][key]) el.textContent=translations[currentLanguage][key];
    });
    updateSoilTypeOptions();
    updateLocationControls();
    if(!$("labModal").classList.contains("hidden")) populateStates();
}
languageSelect.addEventListener("change",e=>changeLanguage(e.target.value));

function updateSoilTypeOptions(){
    document.querySelectorAll("#soilType option[data-i18n]").forEach(o=>{
        const key=o.dataset.i18n;if(t(key))o.textContent=t(key);
    });
}
function updateLocationControls(){
    if($("stateSelect").options.length===0) populateStates();
}

function openModal(modal){modal.classList.remove("hidden")}
function closeModal(modal){modal.classList.add("hidden")}
imageAnalysisBtn.onclick=()=>openModal(imageModal);
manualAnalysisBtn.onclick=()=>openModal(manualModal);
kitBtn.onclick=()=>openModal(kitModal);
labBtn.onclick=()=>{openModal(labModal);populateStates()};
document.querySelectorAll("[data-close]").forEach(btn=>btn.addEventListener("click",()=>closeModal($(btn.dataset.close))));
[imageModal,manualModal,kitModal,labModal].forEach(m=>m.addEventListener("click",e=>{if(e.target===m)closeModal(m)}));

