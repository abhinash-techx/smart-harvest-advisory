analyzeImageBtn.addEventListener("click",async()=>{
    if(!selectedSoilImage){showError(t("selectImageError"));return}
    if(!selectedSoilImage.type.startsWith("image/")){showError(t("invalidImage"));return}
    if(selectedSoilImage.size>5*1024*1024){showError(t("imageTooLarge"));return}
    showLoading();
    try{
        const base64Image=await convertImageToBase64(selectedSoilImage);
        const response=await fetch("/.netlify/functions/analyze-soil",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({mode:"image",language:currentLanguage,image:base64Image})});
        const data=await response.json().catch(()=>null);
        if(!response.ok||!data?.success)throw new Error(data?.message||"Analysis failed");
        closeModal(imageModal);showResult(data.result);
    }catch(err){console.error(err);showError(t("analysisFailed"))}
});
function convertImageToBase64(file){return new Promise((resolve,reject)=>{const r=new FileReader();r.onload=()=>resolve(r.result);r.onerror=reject;r.readAsDataURL(file)})}

soilForm.addEventListener("submit",async e=>{
    e.preventDefault();
    const soilType=$("soilType").value,ph=$("ph").value,n=$("nitrogen").value,p=$("phosphorus").value,k=$("potassium").value,m=$("moisture").value,location=$("location").value;
    if(!soilType||ph===""||n===""||p===""||k===""||m===""){alert(t("manualRequired"));return}
    showLoading();
    try{
        const response=await fetch("/.netlify/functions/analyze-soil",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({mode:"manual",language:currentLanguage,soilType,ph:Number(ph),nitrogen:Number(n),phosphorus:Number(p),potassium:Number(k),moisture:Number(m),location:location.trim()})});
        const data=await response.json().catch(()=>null);
        if(!response.ok||!data?.success)throw new Error(data?.message||"Analysis failed");
        closeModal(manualModal);showResult(data.result);
    }catch(err){console.error(err);showError(t("analysisFailed"))}
});

function showLoading(){
    soilResult.classList.remove("hidden");
    resultContent.innerHTML=`<div class="loading"><div class="loading-spinner"></div><h3>${escapeHTML(t("analyzing"))}</h3><p>${escapeHTML(t("pleaseWait"))}</p></div>`;
    soilResult.scrollIntoView({behavior:"smooth",block:"start"});
}
function showError(message){
    soilResult.classList.remove("hidden");
    resultContent.innerHTML=`<div class="error-message">${escapeHTML(message)}</div>`;
    soilResult.scrollIntoView({behavior:"smooth",block:"start"});
}
function showResult(result){
    soilResult.classList.remove("hidden");
    if(!result){showError(t("analysisFailed"));return}
    let html="";
    const add=(key,value)=>{
        if(value===undefined||value===null||value==="")return;
        let v=Array.isArray(value)?value.map(x=>`• ${escapeHTML(x)}`).join("<br>"):escapeHTML(value);
        html+=`<div class="result-item"><h3>${escapeHTML(t(key))}</h3><p>${v}</p></div>`;
    };
    add("soilHealth",result.soilHealth);add("soilTypeResult",result.soilType);add("phStatus",result.phStatus);add("nutrientStatus",result.nutrientStatus);add("moistureStatus",result.moistureStatus);add("suitableCrops",result.suitableCrops);add("recommendations",result.recommendations);add("visualAssessment",result.visualAssessment);add("confidence",result.confidence);
    if(!html)html=`<div class="result-item"><p>${escapeHTML(JSON.stringify(result))}</p></div>`;
    resultContent.innerHTML=html;soilResult.scrollIntoView({behavior:"smooth",block:"start"});
}
function escapeHTML(value){return String(value??"").replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;").replace(/'/g,"&#039;")}

