async function findLabs(){
    const state=stateSelect.value,district=districtSelect.value;
    if(!state&&!userLocation){showLabMessage(t("chooseLocationFirst"));return}
    labLoading.classList.remove("hidden");labLoading.innerHTML=`<div class="loading-spinner"></div>${escapeHTML(t("findingLabs"))}`;
    labResults.innerHTML="";
    try{
        const response=await fetch("/.netlify/functions/find-labs",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({state,district,latitude:userLocation?.lat||null,longitude:userLocation?.lon||null})});
        const data=await response.json().catch(()=>null);
        if(!response.ok||!data?.success)throw new Error(data?.message||"Lab search failed");
        renderLabs(data.labs||[]);
    }catch(err){console.error(err);showLabMessage(t("labError"))}
    finally{labLoading.classList.add("hidden")}
}
function showLabMessage(msg){labResults.innerHTML=`<div class="lab-note">${escapeHTML(msg)}</div>`}
function renderLabs(labs){
    if(!labs.length){showLabMessage(t("noLabs"));return}
    labResults.innerHTML=labs.map(l=>{
        const type=l.typeKey==="private"?t("private"):l.typeKey==="icar"?t("icar"):l.typeKey==="government"?t("government"):t("registered");
        const dist=l.distanceKm!=null?`<span class="distance">${escapeHTML(t("distance"))}: ${Number(l.distanceKm).toFixed(1)} km</span>`:"";
        const map=`https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(l.address||`${l.name}, ${l.district||""}, ${l.state||""}`)}`;
        const call=l.phone?`<a class="secondary-btn" href="tel:${escapeHTML(l.phone)}">${escapeHTML(t("call"))}</a>`:"";
        return `<article class="lab-card"><div class="lab-card-header"><div><h3>${escapeHTML(l.name||"Soil Testing Centre")}</h3><span class="lab-type">${escapeHTML(type)}</span></div><div>${dist}</div></div><div class="lab-meta"><strong>${escapeHTML(t("address"))}:</strong> ${escapeHTML(l.address||"Not available")}<br>${l.phone?`<strong>${escapeHTML(t("phone"))}:</strong> ${escapeHTML(l.phone)}`:""}</div><div class="lab-actions-row"><a class="secondary-btn" href="${map}" target="_blank" rel="noopener">${escapeHTML(t("directions"))}</a>${call}</div></article>`;
    }).join("");
}
